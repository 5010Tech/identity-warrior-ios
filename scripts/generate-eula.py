#!/usr/bin/env python3
"""Regenerates constants/eula.ts from the Android app's EULA (res/raw/eula.html).

Usage: python3 scripts/generate-eula.py /path/to/eula.html
The app renders the EULA with plain React Native text (no WebView), so the HTML
is flattened to headings and paragraphs made of bold / underlined text runs.
"""
import json
import re
import sys
from html.parser import HTMLParser


class Flatten(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.blocks, self.block, self.bold, self.underline = [], None, 0, 0

    def handle_starttag(self, tag, attrs):
        if tag in ("p", "h1", "h2", "h3"):
            self.block = {"heading": tag != "p", "runs": []}
        elif tag in ("strong", "b"):
            self.bold += 1
        elif tag == "u":
            self.underline += 1

    def handle_endtag(self, tag):
        if tag in ("p", "h1", "h2", "h3") and self.block is not None:
            self.blocks.append(self.block)
            self.block = None
        elif tag in ("strong", "b"):
            self.bold -= 1
        elif tag == "u":
            self.underline -= 1

    def handle_data(self, data):
        if self.block is None:
            return
        text = re.sub(r"\s+", " ", data.replace(" ", " "))
        if not text:
            return
        run = {"text": text}
        if self.bold > 0:
            run["bold"] = True
        if self.underline > 0:
            run["underline"] = True
        runs = self.block["runs"]
        same = runs and {k: v for k, v in runs[-1].items() if k != "text"} == {
            k: v for k, v in run.items() if k != "text"
        }
        if same:
            runs[-1]["text"] = re.sub(r" +", " ", runs[-1]["text"] + text)
        else:
            runs.append(run)


def main():
    html = open(sys.argv[1], encoding="utf-8").read()
    parser = Flatten()
    parser.feed(html[html.index("<body") :])
    blocks = []
    for block in parser.blocks:
        runs = block["runs"]
        if runs:
            runs[0]["text"] = runs[0]["text"].lstrip()
            runs[-1]["text"] = runs[-1]["text"].rstrip()
        runs = [r for r in runs if r["text"]]
        if not "".join(r["text"] for r in runs).strip():
            continue
        out = {"runs": runs}
        if block["heading"]:
            out = {"heading": True, "runs": runs}
        blocks.append(out)
    body = json.dumps(blocks, ensure_ascii=False, indent=2)
    sys.stdout.write(
        "// Generated by scripts/generate-eula.py from the Android app's\n"
        "// res/raw/eula.html. Do not edit by hand; regenerate instead.\n\n"
        "export interface EulaRun {\n  text: string;\n  bold?: boolean;\n  underline?: boolean;\n}\n\n"
        "export interface EulaBlock {\n  heading?: boolean;\n  runs: EulaRun[];\n}\n\n"
        f"export const EULA_BLOCKS: EulaBlock[] = {body};\n"
    )


if __name__ == "__main__":
    main()
